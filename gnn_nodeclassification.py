class GNNEvaluator:
    """Evaluate GNN performance"""

    @staticmethod
    def plot_training_history(losses, accuracies, val_accuracies=None):
        """Plot training curves"""
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4))

        # Loss
        ax1.plot(losses, linewidth=2)
        ax1.set_xlabel('Epoch', fontsize=12)
        ax1.set_ylabel('Loss', fontsize=12)
        ax1.set_title('Training Loss', fontsize=14)
        ax1.grid(True, alpha=0.3)

        # Accuracy
        ax2.plot(accuracies, label='Train', linewidth=2)
        if val_accuracies:
            ax2.plot(val_accuracies, label='Validation', linewidth=2)
        ax2.set_xlabel('Epoch', fontsize=12)
        ax2.set_ylabel('Accuracy', fontsize=12)
        ax2.set_title('Model Accuracy', fontsize=14)
        ax2.legend()
        ax2.grid(True, alpha=0.3)

        plt.tight_layout()
        plt.show()

    @staticmethod
    def plot_node_embeddings(embeddings, labels):
        """Visualize node embeddings in 2D using PCA"""
        from sklearn.decomposition import PCA

        # Reduce to 2D
        pca = PCA(n_components=2)
        emb_2d = pca.fit_transform(embeddings)

        # Plot
        plt.figure(figsize=(10, 8))
        scatter = plt.scatter(emb_2d[:, 0], emb_2d[:, 1],
                             c=labels, cmap='coolwarm',
                             s=100, alpha=0.6, edgecolors='black')
        plt.colorbar(scatter, label='Community')
        plt.xlabel('PC1', fontsize=12)
        plt.ylabel('PC2', fontsize=12)
        plt.title('Node Embeddings (PCA Visualization)', fontsize=14)
        plt.grid(True, alpha=0.3)
        plt.show()

    @staticmethod
    def evaluate_link_prediction(model, graph, train_edges, test_edges):
        """Evaluate link prediction performance"""
        predictions = []
        true_labels = []

        for i, j, label in test_edges:
            prob = model.predict_link(graph, i, j)
            predictions.append(prob)
            true_labels.append(label)

        predictions = np.array(predictions)
        true_labels = np.array(true_labels)

        # Binary predictions
        pred_labels = (predictions > 0.5).astype(int)

        # Metrics
        accuracy = accuracy_score(true_labels, pred_labels)
        auc = roc_auc_score(true_labels, predictions)

        print(f"\nLink Prediction Results:")
        print(f"  Accuracy: {accuracy:.4f}")
        print(f"  AUC-ROC: {auc:.4f}")

        return accuracy, auc


