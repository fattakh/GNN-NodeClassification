class Graph:
    """
    Simple graph data structure for GNN
    """

    def __init__(self, num_nodes):
        """
        Initialize graph

        Args:
            num_nodes: Number of nodes in the graph
        """
        self.num_nodes = num_nodes
        self.adjacency_list = [[] for _ in range(num_nodes)]
        self.node_features = None
        self.node_labels = None

    def add_edge(self, u, v):
        """Add undirected edge between u and v"""
        if v not in self.adjacency_list[u]:
            self.adjacency_list[u].append(v)
        if u not in self.adjacency_list[v]:
            self.adjacency_list[v].append(u)

    def add_edges(self, edges):
        """Add multiple edges"""
        for u, v in edges:
            self.add_edge(u, v)

    def get_neighbors(self, node):
        """Get neighbors of a node"""
        return self.adjacency_list[node]

    def get_adjacency_matrix(self):
        """Get dense adjacency matrix"""
        adj = np.zeros((self.num_nodes, self.num_nodes))
        for i in range(self.num_nodes):
            for j in self.adjacency_list[i]:
                adj[i, j] = 1
        return adj

    def normalize_adjacency(self):
        """Normalize adjacency matrix (D^(-1/2) A D^(-1/2))"""
        adj = self.get_adjacency_matrix()
        degrees = np.sum(adj, axis=1)
        D_inv_sqrt = np.diag(1.0 / np.sqrt(degrees + 1e-8))
        adj_norm = D_inv_sqrt @ adj @ D_inv_sqrt
        return adj_norm

    def set_node_features(self, features):
        """Set node features"""
        self.node_features = features

    def set_node_labels(self, labels):
        """Set node labels"""
        self.node_labels = labels

    def visualize(self, node_colors=None, title="Graph Visualization"):
        """Visualize the graph"""
        G = nx.Graph()

        # Add nodes
        for i in range(self.num_nodes):
            G.add_node(i)

        # Add edges
        for i in range(self.num_nodes):
            for j in self.adjacency_list[i]:
                if i < j:  # Add each edge once
                    G.add_edge(i, j)

        # Create layout
        pos = nx.spring_layout(G, seed=42)

        # Plot
        plt.figure(figsize=(10, 8))

        if node_colors is not None:
            nx.draw(G, pos, node_color=node_colors,
                   node_size=500, cmap='coolwarm',
                   with_labels=True, font_size=10,
                   edge_color='gray', alpha=0.7)
        else:
            nx.draw(G, pos, node_color='lightblue',
                   node_size=500, with_labels=True,
                   edge_color='gray', alpha=0.7)

        plt.title(title, fontsize=14)
        plt.axis('off')
        plt.tight_layout()
        plt.show()


