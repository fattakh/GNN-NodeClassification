class SocialNetworkDataset:
    """
    Generate synthetic social network dataset for friend recommendation
    """

    def __init__(self, num_nodes=100, num_communities=3, avg_degree=5):
        """
        Generate social network graph

        Args:
            num_nodes: Number of users
            num_communities: Number of interest groups
            avg_degree: Average number of friends
        """
        self.num_nodes = num_nodes
        self.num_communities = num_communities
        self.graph = Graph(num_nodes)

        # Assign nodes to communities
        self.communities = np.random.randint(0, num_communities, num_nodes)

        # Generate edges (friendships) based on communities
        # Higher probability within same community
        edges = []
        for i in range(num_nodes):
            for j in range(i+1, num_nodes):
                if self.communities[i] == self.communities[j]:
                    prob = avg_degree / num_nodes * 5  # Higher within community
                else:
                    prob = avg_degree / num_nodes  # Lower between communities

                if np.random.random() < prob:
                    edges.append((i, j))

        self.graph.add_edges(edges)

        # Generate node features (user profiles)
        # Features: age, activity level, interests (one-hot for community)
        self.features = np.zeros((num_nodes, num_communities + 2))
        for i in range(num_nodes):
            # Age (normalized)
            self.features[i, 0] = np.random.uniform(18, 65) / 65
            # Activity level
            self.features[i, 1] = np.random.uniform(0, 1)
            # Interest in each community
            for c in range(num_communities):
                if self.communities[i] == c:
                    self.features[i, 2 + c] = 1.0
                else:
                    self.features[i, 2 + c] = 0.2  # Some interest in other communities

        self.graph.set_node_features(self.features)

        # Node labels: community membership
        self.graph.set_node_labels(self.communities)

        # Create train/val masks (70% train, 30% val)
        self.train_mask = np.zeros(num_nodes, dtype=bool)
        self.val_mask = np.zeros(num_nodes, dtype=bool)

        indices = np.arange(num_nodes)
        np.random.shuffle(indices)
        split = int(0.7 * num_nodes)
        self.train_mask[indices[:split]] = True
        self.val_mask[indices[split:]] = True

    def get_graph(self):
        """Return the graph"""
        return self.graph

    def get_train_val_masks(self):
        """Return train and validation masks"""
        return self.train_mask, self.val_mask

    def get_link_data(self, positive_ratio=0.5):
        """Generate link prediction dataset - FIXED VERSION"""
        # Positive examples (existing edges)
        positive_edges = []
        for i in range(self.num_nodes):
            for j in self.graph.adjacency_list[i]:
                if i < j:  # Add each edge only once
                    positive_edges.append((i, j))

        # Create labels for positive edges
        positive_pairs = [(i, j, 1) for i, j in positive_edges]

        # Negative examples (non-edges)
        all_pairs = set()
        for i in range(self.num_nodes):
            for j in range(i+1, self.num_nodes):
                all_pairs.add((i, j))

        existing_pairs = set(positive_edges)
        non_edges = list(all_pairs - existing_pairs)

        # Sample negative examples
        num_negatives = int(len(positive_edges) * (1 - positive_ratio) / positive_ratio)
        num_negatives = min(num_negatives, len(non_edges))

        if num_negatives > 0:
            sampled_negatives = np.random.choice(len(non_edges), num_negatives, replace=False)
            negative_pairs = [(non_edges[idx][0], non_edges[idx][1], 0) for idx in sampled_negatives]
        else:
            negative_pairs = []

        # Combine
        all_edges = positive_pairs + negative_pairs
        np.random.shuffle(all_edges)

        # Split into train/test
        split = int(0.8 * len(all_edges))
        train_edges = all_edges[:split]
        test_edges = all_edges[split:]

        return train_edges, test_edges

    def visualize_communities(self):
        """Visualize graph with community colors"""
        colors = self.communities
        self.graph.visualize(node_colors=colors, title="Social Network Communities")


