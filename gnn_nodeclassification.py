class GraphNeuralNetwork:
    """
    Complete Graph Neural Network with multiple layers
    """

    def __init__(self, layer_dims, task='node_classification'):
        """
        Initialize GNN

        Args:
            layer_dims: List of dimensions [input_dim, hidden_dim1, ..., output_dim]
            task: 'node_classification' or 'link_prediction'
        """
        self.layer_dims = layer_dims
        self.task = task
        self.num_layers = len(layer_dims) - 1

        # Create GCN layers
        self.layers = []
        for i in range(self.num_layers):
            activation = 'relu' if i < self.num_layers - 1 else None
            self.layers.append(
                GraphConvolutionLayer(layer_dims[i], layer_dims[i+1], activation)
            )

        # Store cache
        self.cache = {}

    def forward(self, H, A_norm):
        """
        Forward pass through all layers

        Args:
            H: Node features (N x input_dim)
            A_norm: Normalized adjacency matrix (N x N)

        Returns:
            H_final: Node embeddings (N x output_dim)
        """
        for i, layer in enumerate(self.layers):
            H = layer.forward(H, A_norm)
            self.cache[f'layer_{i}_output'] = H

        return H

    def backward(self, dH_final):
        """
        Backward pass through all layers

        Args:
            dH_final: Gradient from loss function

        Returns:
            Gradients for all layers
        """
        dH = dH_final
        grads = []

        for i in range(len(self.layers) - 1, -1, -1):
            dH, dW, db = self.layers[i].backward(dH)
            grads.insert(0, (dW, db))

        return grads

    def train_node_classification(self, graph, train_mask, val_mask,
                                  epochs=200, learning_rate=0.01, verbose=True):
        """
        Train for node classification

        Args:
            graph: Graph object
            train_mask: Boolean mask for training nodes
            val_mask: Boolean mask for validation nodes
            epochs: Number of training epochs
            learning_rate: Learning rate
            verbose: Print progress
        """
        # Prepare data
        A_norm = graph.normalize_adjacency()
        H = graph.node_features
        y = graph.node_labels

        # Convert labels to one-hot
        num_classes = len(np.unique(y))
        y_onehot = np.zeros((graph.num_nodes, num_classes))
        y_onehot[np.arange(graph.num_nodes), y] = 1

        # Training loop
        losses = []
        accuracies = []
        val_accuracies = []

        for epoch in range(epochs):
            # Forward pass
            H_final = self.forward(H, A_norm)

            # Compute loss (cross-entropy on training nodes)
            logits = H_final[train_mask]
            y_train = y_onehot[train_mask]

            # Softmax
            exp_logits = np.exp(logits - np.max(logits, axis=1, keepdims=True))
            probs = exp_logits / np.sum(exp_logits, axis=1, keepdims=True)

            # Cross-entropy loss
            loss = -np.mean(np.sum(y_train * np.log(probs + 1e-8), axis=1))
            losses.append(loss)

            # Backward pass
            dH_final = np.zeros_like(H_final)
            dH_final[train_mask] = probs - y_train
            grads = self.backward(dH_final)

            # Update weights
            for i, (dW, db) in enumerate(grads):
                self.layers[i].W -= learning_rate * dW
                self.layers[i].b -= learning_rate * db

            # Evaluate
            train_pred = np.argmax(H_final[train_mask], axis=1)
            train_true = y[train_mask]
            train_acc = np.mean(train_pred == train_true)
            accuracies.append(train_acc)

            val_acc = 0
            if val_mask is not None:
                val_pred = np.argmax(H_final[val_mask], axis=1)
                val_true = y[val_mask]
                val_acc = np.mean(val_pred == val_true)
                val_accuracies.append(val_acc)

            if verbose and (epoch % 20 == 0 or epoch == epochs-1):
                val_str = f", Val Acc: {val_acc:.4f}" if val_mask is not None else ""
                print(f"Epoch {epoch:3d}/{epochs} - Loss: {loss:.4f}, "
                      f"Train Acc: {train_acc:.4f}{val_str}")

        return losses, accuracies, val_accuracies

    def predict_node_labels(self, graph):
        """Predict node labels"""
        A_norm = graph.normalize_adjacency()
        H = graph.node_features
        H_final = self.forward(H, A_norm)
        return np.argmax(H_final, axis=1)

    def predict_link(self, graph, node1, node2):
        """Predict link between two nodes"""
        A_norm = graph.normalize_adjacency()
        H = graph.node_features
        H_final = self.forward(H, A_norm)

        # Compute similarity between node embeddings
        emb1 = H_final[node1]
        emb2 = H_final[node2]

        # Cosine similarity
        similarity = np.dot(emb1, emb2) / (np.linalg.norm(emb1) * np.linalg.norm(emb2) + 1e-8)

        # Sigmoid to get probability
        prob = 1 / (1 + np.exp(-similarity))

        return prob

    def get_node_embeddings(self, graph):
        """Get node embeddings from the last layer"""
        A_norm = graph.normalize_adjacency()
        H = graph.node_features
        H_final = self.forward(H, A_norm)
        return H_final


