class GraphConvolutionLayer:
    """
    Graph Convolution Layer (GCN Layer)
    Implements: H' = σ(A_hat @ H @ W)
    where A_hat = D^(-1/2) A D^(-1/2)
    """

    def __init__(self, input_dim, output_dim, activation='relu'):
        """
        Initialize GCN layer

        Args:
            input_dim: Input feature dimension
            output_dim: Output feature dimension
            activation: Activation function ('relu', 'sigmoid', 'tanh', None)
        """
        self.input_dim = input_dim
        self.output_dim = output_dim
        self.activation = activation

        # Initialize weights (Xavier initialization)
        self.W = np.random.randn(input_dim, output_dim) * np.sqrt(2.0 / input_dim)
        self.b = np.zeros(output_dim)

        # Cache for backprop
        self.cache = {}

    def forward(self, H, A_norm):
        """
        Forward pass

        Args:
            H: Node features (N x input_dim)
            A_norm: Normalized adjacency matrix (N x N)

        Returns:
            H_next: Updated node features (N x output_dim)
        """
        # Message passing: A_norm @ H
        H_aggregated = A_norm @ H

        # Linear transformation: (A_norm @ H) @ W + b
        H_linear = H_aggregated @ self.W + self.b

        # Activation
        if self.activation == 'relu':
            H_next = np.maximum(0, H_linear)
            self.cache['derivative'] = (H_linear > 0).astype(float)
        elif self.activation == 'sigmoid':
            H_next = 1 / (1 + np.exp(-H_linear))
            self.cache['derivative'] = H_next * (1 - H_next)
        elif self.activation == 'tanh':
            H_next = np.tanh(H_linear)
            self.cache['derivative'] = 1 - H_next**2
        else:
            H_next = H_linear
            self.cache['derivative'] = np.ones_like(H_linear)

        # Cache for backprop
        self.cache['H'] = H
        self.cache['H_aggregated'] = H_aggregated
        self.cache['H_linear'] = H_linear
        self.cache['A_norm'] = A_norm

        return H_next

    def backward(self, dH_next):
        """
        Backward pass

        Args:
            dH_next: Gradient from next layer (N x output_dim)

        Returns:
            dH: Gradient for previous layer (N x input_dim)
            dW: Gradient for weights (input_dim x output_dim)
            db: Gradient for bias (output_dim,)
        """
        # Gradient through activation
        dH_linear = dH_next * self.cache['derivative']

        # Gradient for bias
        db = np.sum(dH_linear, axis=0)

        # Gradient for weights
        dW = self.cache['H_aggregated'].T @ dH_linear

        # Gradient for aggregated features
        dH_aggregated = dH_linear @ self.W.T

        # Gradient through message passing
        A_norm = self.cache['A_norm']
        dH = A_norm.T @ dH_aggregated

        return dH, dW, db


